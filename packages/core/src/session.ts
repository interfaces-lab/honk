/**
 * The session service as in-process callers use it.
 *
 * Every request/response method type derives from its {@link Rpc} through
 * {@link Method}, so the service cannot drift from the wire contract.
 *
 * @category service
 */
export interface Interface {
  readonly create: Method<typeof Create>;
  readonly prompt: Method<typeof Prompt>;
  readonly abort: Method<typeof Abort>;
  readonly steer: Method<typeof Steer>;
  readonly followUp: Method<typeof FollowUp>;
  readonly reload: Method<typeof Reload>;
  readonly changes: Method<typeof Changes>;
  readonly setWorkspace: Method<typeof SetWorkspace>;
  readonly revert: Method<typeof Revert>;
  readonly list: Method<typeof List>;
  readonly get: Method<typeof Get>;
  readonly delete: Method<typeof Delete>;

  /**
   * Subscribes to this session's events.
   *
   * Two-stage on purpose. The outer Effect resolves only *after* the
   * subscription is live, which is what makes "start listening, then reload"
   * deterministic: every event published after it completes reaches the
   * returned stream. A single-stage API that returned a lazy stream could not
   * express that guarantee, because the caller would not know when listening
   * began.
   *
   * The `Scope` owns the subscription. Closing it detaches the client without
   * touching the run.
   */
  readonly events: (input: {
    readonly sessionId: SessionId;
  }) => Effect.Effect<
    Stream.Stream<AgentHarnessEvent>,
    NotFoundError | PiError | Models.ResolveError,
    Scope.Scope
  >;
}

