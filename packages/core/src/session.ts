/**
 * What did *this* conversation change, turn by turn?
 *
 * A workspace answers "what changed here"; a thread must answer "what did this
 * conversation change", and those differ the moment two sessions share a
 * directory. `changes` is the second question, at turn granularity.
 *
 * Each settled turn captured a workspace checkpoint, and a turn's changes are
 * the diff between its checkpoint and the one before it — so shell writes and
 * generated files appear, not just tool-declared edits. The tool calls of the
 * turn act as an attribution gate over that diff: a turn that used only
 * declaring tools claims only the paths it named, which is what keeps a
 * sibling session's edits (or the user's own) out of this turn's receipt. A
 * turn that ran an opaque mutator — shell, an MCP tool — claims the whole
 * diff, because filtering it would silently hide real writes.
 *
 * It stores nothing beyond the checkpoints themselves: the answer is
 * recomputed from the git object store and the committed transcript. A
 * workspace without a repository has no checkpoints and honestly reports no
 * turns.
 *
 * Content diffs are not here. `changes` answers *which* paths per turn;
 * `sdk.git.checkpointDiff` answers *what* changed in them.
 *
 * @example
 * ```ts
 * const { turns } = await sdk.session.changes({ sessionId });
 * for (const turn of turns) {
 *   renderReceipt(turn.entryId, turn.files);
 * }
 * ```
 *
 * @category commands
 */
export const Changes = Rpc.make("session.changes", {
  payload: { sessionId: SessionId },
  success: ChangesOutput,
  error: LookupError,
});

/**
 * Moves the session to another trusted workspace — `/cd`.
 *
 * Holding a `WorkspaceId` proves a trust decision was made, so there is no
 * second permission gate here: an unknown id and an untrusted directory are
 * the same refusal. The move takes effect at the next turn — Pi resolves the
 * harness tool context per turn snapshot, so a run already in progress
 * finishes in the directory it started in.
 *
 * The move is recorded in the Pi transcript as a custom entry (out of model
 * context, like Pi's own model-change entries), and a fresh checkpoint is
 * captured in the new workspace so the next turn's changes diff against the
 * directory as the session found it.
 *
 * @category commands
 */
export const SetWorkspace = Rpc.make("session.set_workspace", {
  payload: { sessionId: SessionId, workspaceId: Workspace.WorkspaceId },
  error: Schema.Union([LookupError, Workspace.NotFoundError]),
});

/**
 * Rewrites the workspace to the checkpoint a turn captured.
 *
 * `entryId` names a turn from {@link Changes}, or `"base"` for the state the
 * session found the workspace in. The revert is recorded in the transcript as
 * a custom entry, and a safety checkpoint of the present is captured under
 * that entry first — so a revert is itself revertible, and the undo is a
 * revert to the entry the revert created.
 *
 * Destructive for the working tree, never for the transcript: the
 * conversation keeps every turn, and only the files move. The client decides
 * whether to also steer the conversation.
 *
 * @category commands
 */
export const Revert = Rpc.make("session.revert", {
  payload: { sessionId: SessionId, entryId: Schema.NonEmptyString },
  error: Schema.Union([LookupError, Git.Failure]),
});

